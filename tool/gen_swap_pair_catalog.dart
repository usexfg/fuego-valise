// Swap pair catalog generator.
//
// Reads fuego-suite/src/SwapDaemon/SwapPairCatalog.h (the append-only wire
// catalog xfg-swapd speaks) and emits lib/models/swap_pair_catalog.g.dart, so
// the wallet's pair ids, catalog keys and support levels come from the daemon
// rather than a hand-kept copy.
//
// Usage:
//   dart run tool/gen_swap_pair_catalog.dart          # (re)generate
//   dart run tool/gen_swap_pair_catalog.dart --check  # exit 1 on drift

import 'dart:io';

import 'gen_chains.dart' show dartFormat;

const String catalogPath = 'fuego-suite/src/SwapDaemon/SwapPairCatalog.h';
const String outPath = 'lib/models/swap_pair_catalog.g.dart';

final RegExp catalogRow = RegExp(
  r'^\s*X\(\s*([A-Z_0-9]+)\s*,\s*(\d+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,'
  r'\s*"([^"]*)"\s*,\s*([A-Z0-9_]+)\s*,\s*(\d+)\s*,\s*\d+\s*,\s*\d+\s*,'
  r'\s*(\d+)\s*,\s*([A-Z_]+)\s*,',
  multiLine: true,
);

class CatalogRow {
  CatalogRow(
    this.name,
    this.id,
    this.key,
    this.asset,
    this.display,
    this.family,
    this.chainId,
    this.decimals,
    this.support,
  );
  final String name;
  final int id;
  final String key;
  final String asset;
  final String display;
  final String family;
  final int chainId;
  final int decimals;
  final String support;
}

List<CatalogRow> parseCatalog(String header) {
  final rows = [
    for (final m in catalogRow.allMatches(header))
      CatalogRow(
        m.group(1)!,
        int.parse(m.group(2)!),
        m.group(3)!,
        m.group(4)!,
        m.group(5)!,
        m.group(6)!.toLowerCase(),
        int.parse(m.group(7)!),
        int.parse(m.group(8)!),
        m.group(9)!.toLowerCase(),
      ),
  ];
  for (var i = 0; i < rows.length; i++) {
    if (rows[i].id != i) {
      throw StateError('catalog ids are not contiguous at row $i');
    }
  }
  if (rows.isEmpty) throw StateError('no catalog rows found in $catalogPath');
  return rows;
}

String _str(String s) =>
    "'${s.replaceAll('\\', r'\\').replaceAll("'", r"\'")}'";

String render(List<CatalogRow> rows) {
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_swap_pair_catalog.dart from')
    ..writeln('// $catalogPath. Do not edit; regenerate.')
    ..writeln()
    ..writeln('/// One wire id of xfg-swapd\'s append-only swap pair catalog.')
    ..writeln('class SwapPairCatalogEntry {')
    ..writeln(
      '  const SwapPairCatalogEntry(this.id, this.name, this.key, this.asset,',
    )
    ..writeln(
      '      this.display, this.family, this.chainId, this.decimals, this.support);',
    )
    ..writeln('  final int id;')
    ..writeln('  final String name;')
    ..writeln('  final String key;')
    ..writeln('  final String asset;')
    ..writeln('  final String display;')
    ..writeln('  final String family;')
    ..writeln('  final int chainId;')
    ..writeln('  final int decimals;')
    ..writeln('  /// active | adapter | gated | staged')
    ..writeln('  final String support;')
    ..writeln()
    ..writeln('  /// The id is carried on the wire and in swap records.')
    ..writeln("  bool get protocol => support != 'staged';")
    ..writeln('}')
    ..writeln()
    ..writeln('const List<SwapPairCatalogEntry> kSwapPairCatalog = [');
  for (final r in rows) {
    b.writeln(
      '  SwapPairCatalogEntry(${r.id}, ${_str(r.name)}, ${_str(r.key)}, '
      '${_str(r.asset)}, ${_str(r.display)}, ${_str(r.family)}, ${r.chainId}, '
      '${r.decimals}, ${_str(r.support)}),',
    );
  }
  b.writeln('];');
  return b.toString();
}

void main(List<String> args) {
  final header = File(catalogPath);
  if (!header.existsSync()) {
    stderr.writeln(
      '$catalogPath missing: run git submodule update --init fuego-suite',
    );
    exit(1);
  }
  final code = dartFormat(render(parseCatalog(header.readAsStringSync())));
  final out = File(outPath);
  if (!args.contains('--check')) {
    out.writeAsStringSync(code);
    stdout.writeln('Wrote $outPath.');
    return;
  }
  if (out.existsSync() && out.readAsStringSync() == code) {
    stdout.writeln('OK: $outPath matches $catalogPath.');
    return;
  }
  stderr.writeln('DRIFT: $outPath does not match $catalogPath.');
  stderr.writeln('Run: dart run tool/gen_swap_pair_catalog.dart');
  exit(1);
}
